#pragma once

#include <string>

// Минимальный HTTP-сервер службы. Слушает все интерфейсы, чтобы интерфейс на консоли
// (127.0.0.1) и проверки с телефона/ПК работали одинаково. Маршруты:
//   GET  /health   версия службы, состояние BGFT
//   GET  /scan     найденные .pkg в /data/pkg и /mnt/usbN
//   GET  /free     свободное место
//   POST /install  {"paths":["/data/pkg/a.pkg", ...]} - поставить в очередь (от большего к меньшему)
//   GET  /status   очередь, ход установки, последние строки журнала
//   POST /cancel   снять с очереди ещё не начатое
//   POST /quit     завершить службу (так новая копия вытесняет старую)

// Возвращает 0 при нормальном завершении. Блокирует поток до /quit.
int http_serve(int port);

// Просит уже запущенную копию на этом порту завершиться (единственный экземпляр).
void http_request_quit(int port);
