#pragma once
// Загрузка по адресу http:// или https://.
//  http://  - обычным клиентом приложения (httpc); в основном для проверок на ПК.
//  https:// - системными библиотеками приставки libSceHttp / libSceSsl (подгружаются через dlopen). Рукопожатие TLS, проверку
//             сертификата и переходы по ссылкам (302, как у GitHub Releases) делает библиотека. Каждый шаг пишется в журнал.
//             НЕ ПРОВЕРЕНО НА КОНСОЛИ: имена функций и порядок вызовов взяты по памяти.
// Проверку сертификата не отключаем: если библиотека не принимает сертификат, загрузка не удаётся.
#include <string>

// Скачивает url в память (не больше maxBytes). true - получили ответ 200. err - причина неудачи (для журнала).
bool https_get(const std::string& url, std::string& body, size_t maxBytes, std::string& err);
